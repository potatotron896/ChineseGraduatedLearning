import type { HskLevel, StoryToken } from "../types/story";
import { CHARACTER_DICTIONARY, getCharacterEtymology } from "./character-dictionary";

export interface LexiconEntry {
  pinyin: string;
  hskLevel: HskLevel;
  meaningPt: string;
  partOfSpeech: string;
  compoundLogicPt: string;
  charPinyins?: string[];
  charHsks?: HskLevel[];
  charMeanings?: string[];
}

export const PUNCTUATION_SET = new Set(["，", "。", "？", "！", "：", "“", "”", "、", "；", "……", "——"]);

function buildChars(word: string, entry: LexiconEntry) {
  const charsArr = Array.from(word);
  return charsArr.map((ch, idx) =>
    CHARACTER_DICTIONARY[ch] ||
    getCharacterEtymology(
      ch,
      entry.charPinyins?.[idx] || entry.pinyin,
      entry.charHsks?.[idx] || entry.hskLevel,
      entry.charMeanings?.[idx] || entry.meaningPt
    )
  );
}

