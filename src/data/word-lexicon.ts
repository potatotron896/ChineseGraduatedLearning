export function tokenize(sentenceId: string, specs: TokenSpec[]): StoryToken[] {
  return specs.map((spec, idx) => {
    const id = `${sentenceId}-t${idx + 1}`;
    const hanzi = typeof spec === "string" ? spec : spec.hanzi;
    const override = typeof spec === "string" ? undefined : spec.override;

    if (PUNCTUATION_SET.has(hanzi)) {
      return { id, hanzi, isPunctuation: true };
    }

    const entry = WORD_LEXICON[hanzi];
    if (!entry) {
      throw new Error(`Missing WORD_LEXICON entry for token "${hanzi}" in sentence "${sentenceId}"`);
    }

    return {
      id,
      hanzi,
      pinyin: entry.pinyin,
      hskLevel: entry.hskLevel,
      meaningPt: entry.meaningPt,
      partOfSpeech: entry.partOfSpeech,
      compoundLogicPt: entry.compoundLogicPt,
      characters: buildChars(hanzi, entry),
      ...override,
    };
  });
}

